# Writes scripts/soak/<level>_s<seed>.txt: a long seeded soak per level of the game's level list. Each script continues the saved hero, loads the
# level directly (`loadlevel`), levels the hero up with the binary's cheat path, then repeats a 5000-frame cycle until the frame budget is used:
#   seeded random play (rand), explore, hunt, loot, a menu cycle (pause/continue, the six hero-screen tabs), two more cheat level-ups,
#   and every second cycle save + quit to the main menu + continue (pause -> main menu -> yes -> Start -> Single player -> tap the loading screen).
# usage: py -3 make_soak_scripts.py <file with the runner's `levels` output> <frames> <seed> [seed...]
import os
import re
import sys

src, frames = sys.argv[1], int(sys.argv[2])
seeds = [int(s) for s in sys.argv[3:]] or [1]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "soak")
os.makedirs(out, exist_ok=True)
names = []
for line in open(src, encoding="latin1"):
    m = re.search(r"\[bot\] level \d+ file=(\S+)", line)
    if m and m.group(1) not in names and m.group(1) != "-":
        names.append(m.group(1))

# Levels the playthrough could not load (see HOST-RUNNER.md): skipped.
skip = {"x50_earth_temple_demo_BACKUP.mlx"}

count = 0
for name in names:
    if name in skip:
        continue
    for seed in seeds:
        L = [f"# soak: {name}, seed {seed}, {frames} frames (generated by make_soak_scripts.py)",
             "60 tap 1000 700", "200 tap 2148 322", "300 tap 2136 368", "420 tap 1200 540",
             "700 auto 1", "700 cheats 1", f"710 loadlevel {name}"]
        L += [f"{f} tap 1200 540" for f in range(900, 1700, 100)]
        L += [f"{1700 + i} cheat LevelUp" for i in range(5)]
        L += ["1710 cheat GiveGold", "1720 herostat", "1720 levelstat loaded"]
        f = 1800
        cycle = 0
        while f + 5000 <= frames:
            c = f
            L += [f"{c} rand {seed * 1000 + cycle} 2400 4000"]
            c += 2400
            L += [f"{c} explore 500"]
            c += 500
            L += [f"{c} hunt 1000 4000"]
            c += 1000
            L += [f"{c} loot 300 4000"]
            c += 320
            # menu cycle: pause, continue; hero screen, every tab, back (twice for the confirm dialog), confirm
            L += [f"{c} idle", f"{c} click 176 340", f"{c + 50} click 1190 340", f"{c + 100} click 260 140"]
            for i, x in enumerate((1250, 1490, 1750, 1990, 2220, 1030)):
                L.append(f"{c + 150 + 40 * i} click {x} 56")
            L += [f"{c + 420} click 80 56", f"{c + 450} click 900 560", f"{c + 480} click 80 56"]
            c += 520
            L += [f"{c} cheat LevelUp", f"{c + 1} cheat LevelUp", f"{c + 2} herostat"]
            c += 10
            if cycle % 2 == 1:
                # save + quit to the main menu + continue
                L += [f"{c} click 176 340", f"{c + 60} click 1190 678", f"{c + 120} click 912 604",
                      f"{c + 300} tap 2148 322", f"{c + 400} tap 2136 368"]
                L += [f"{c + 500 + 100 * k} tap 1200 540" for k in range(6)]
            L += [f"{f + 4990} levelstat cycle{cycle}"]
            f += 5000
            cycle += 1
        L += [f"{f} levelstat end", f"{f + 10} quit"]
        with open(os.path.join(out, f"{name.replace('.', '_')}_s{seed}.txt"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(L) + "\n")
        count += 1
print(count, "soak scripts in", out)
