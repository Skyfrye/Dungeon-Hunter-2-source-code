# Writes scripts/levels/<level>.txt: one playthrough script per entry of the game's level list (Arrays::LevelList, printed by the runner's
# `levels` command). Each script continues the saved hero, loads the level directly (`loadlevel`, the FS_LoadLevel path), taps through the
# loading screen, then explores, hunts, loots and follows the level's route (checkpoint zones, then the exit zone, whose fast-travel button it presses), with a `levelstat` line after every phase.
# usage: py -3 make_level_scripts.py <file with the `levels` output> [out dir]
import os
import re
import sys

src = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "levels")
os.makedirs(out, exist_ok=True)
names = []
for line in open(src, encoding="latin1"):
    m = re.search(r"\[bot\] level \d+ file=(\S+)", line)
    if m and m.group(1) not in names and m.group(1) != "-":
        names.append(m.group(1))

for name in names:
    lines = [
        f"# level playthrough: {name} (generated by make_level_scripts.py)",
        "60 tap 1000 700",
        "200 tap 2148 322",
        "300 tap 2136 368",
        "420 tap 1200 540",
        "700 levelstat start",
        "700 auto 1",
        f"710 loadlevel {name}",
    ]
    lines += [f"{f} tap 1200 540" for f in range(900, 1700, 100)]
    lines += [
        "1700 levelstat loaded",
        "1700 enemies",
        "1700 badbools",
        "1710 explore 600",
        "2310 levelstat explore",
        "2320 hunt 1500 4000",
        "3820 levelstat hunt",
        "3830 loot 600 4000",
        "4430 levelstat loot",
        "4440 route 3000",
        "7440 levelstat exit",
        "7450 quit",
    ]
    with open(os.path.join(out, name.replace(".", "_") + ".txt"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
print(len(names), "scripts in", out)
