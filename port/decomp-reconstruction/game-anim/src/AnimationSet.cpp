// 0x3649e0 _ZN12AnimationSet19_FindCacheCandidateEv
// Walks the entries in key order, as the original walks its tree in order. An entry with a positive use count
// (Animation +0x24, m_useCount) is skipped. Among the others the lowest counter (+0x2c, unk_2c, compared as
// unsigned) wins, and an equal counter goes to the entry with the older last-use stamp (+0x28, m_lastUseTime).
// The comparison values are seeded from the first entry, as the original seeds them from the leftmost node, so
// that entry is chosen only by a later comparison. When nothing is chosen the result is the key of the first
// entry that is not in use, and -1 when every entry is in use or the set is empty.
int AnimationSet::_FindCacheCandidate() {
    int candidate = -1;
    int fallback = -1;
    if (m_animations.empty()) {
        return fallback;
    }
    auto node = m_animations.begin();
    std::uint32_t bestCounter = static_cast<std::uint32_t>(node->second.unk_2c);
    std::uint32_t bestStamp = node->second.m_lastUseTime;
    for (; node != m_animations.end(); ++node) {
        const Animation& entry = node->second;
        if (entry.m_useCount > 0) {
            continue;
        }
        if (fallback == -1) {
            fallback = node->first;
        }
        const std::uint32_t counter = static_cast<std::uint32_t>(entry.unk_2c);
        if (counter < bestCounter) {
            bestCounter = counter;
            bestStamp = entry.m_lastUseTime;
            candidate = node->first;
        } else if (counter == bestCounter && bestStamp > entry.m_lastUseTime) {
            bestStamp = entry.m_lastUseTime;
            candidate = node->first;
        }
    }
    return candidate != -1 ? candidate : fallback;
}

// 0x364af4 _ZN12AnimationSet23_UpdateAnimationIndicesEv
// Refreshes the library index of every entry from the engine set (CDynamicAnimationSet::getDatabaseIndex of its database).
void AnimationSet::_UpdateAnimationIndices() {
    for (auto node = m_animations.begin(); node != m_animations.end(); ++node) {
        node->second.unk_20 = m_animSet->getDatabaseIndex(node->second.m_database);
    }
}

// 0x364bf4 _ZN12AnimationSet22GetAnimationBySetIndexEi
// Scans the entries in key order for the first one whose set index (Animation +0x20, unk_20 in dh2/Animation.hpp)
// equals setIndex. A hit stamps that entry's last-use time (+0x28) from glitch::os::Timer::getRealTime() and
// returns it. A miss returns the invalid entry.
Animation* AnimationSet::GetAnimationBySetIndex(int setIndex) {
    for (auto node = m_animations.begin(); node != m_animations.end(); ++node) {
        if (node->second.unk_20 == setIndex) {
            node->second.m_lastUseTime = glitch::os::Timer::getRealTime();
            return &node->second;
        }
    }
    return &s_invalidAnim;
}

// 0x364ca0 _ZN12AnimationSet13CreateAnimSetEv
// Drops the previous engine set, sets the flag at +0x2c and builds a new CDynamicAnimationSet (operator new(0x80)) with
// setMismatchBehavior(1) (vtable +0x1c). The original returns the r0 of that call (a reference, a register residue); the int
// return carries 0.
int AnimationSet::CreateAnimSet() {
    if (m_animSet) {
        m_animSet->drop();
        m_animSet = nullptr;
    }
    unk_2c = 1;
    auto* set = new glitch::collada::CDynamicAnimationSet();
    m_animSet = set;
    (void)set->setMismatchBehavior(static_cast<glitch::collada::CAnimationSet::E_MISMATCH_BEHAVIOR>(1));
    return 0;
}

// 0x364ecc _ZN12AnimationSet7FreeAllEv
// partial: the original releases m_animSet through glitch::IReferenceCounted::drop before clearing it. The
// release needs glitch::IReferenceCounted as a base of CDynamicAnimationSet (layout request), so only the pointer
// is cleared. The tree part is reproduced: erasing every node and resetting the header is std::map::clear, and
// each erased Animation runs its destructor.
void AnimationSet::FreeAll() {
    if (m_animSet) {
        m_animSet->drop();
        m_animSet = nullptr;
    }
    m_animations.clear();
}

