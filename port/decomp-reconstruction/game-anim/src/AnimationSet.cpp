// 0x36504c _ZN12AnimationSet16_RemoveAnimationENSt4priv17_Rb_tree_iteratorISt4pairIKi9AnimationENS0_11_MapTraitsTIS5_EEEEb
// The entry library binding is released on the engine set: the whole library when the set is dirty (+0x70), only its bindings
// otherwise; the entry is erased unless keepEntry.
void AnimationSet::_RemoveAnimation(std::map<int, Animation>::iterator node, bool keepEntry) {
    if (m_animSet) {
        if (m_animSet->dirty) {
            m_animSet->remAnimationLibrary(static_cast<unsigned int>(node->second.unk_20));
        } else {
            m_animSet->remAnimationLibraryBindings(static_cast<unsigned int>(node->second.unk_20));
        }
    }
    if (!keepEntry) {
        m_animations.erase(node);
    }
}

// 0x3650b4 _ZN12AnimationSet15UnloadAnimationEib
// Finds the entry for animId. A missing entry, or one whose use count (Animation +0x24, m_useCount) is positive,
// returns false and changes nothing. Otherwise the entry goes through _RemoveAnimation (kept when keepEntry is
// set), the set indices are refreshed by _UpdateAnimationIndices, and the result is true. The original's
// lower_bound plus key test is find(). Both callees are partial (see their notes), so the library release and
// the index refresh are not yet complete; this body is the original's.
bool AnimationSet::UnloadAnimation(int animId, bool keepEntry) {
    const auto node = m_animations.find(animId);
    if (node == m_animations.end()) {
        return false;
    }
    if (node->second.m_useCount > 0) {
        return false;
    }
    _RemoveAnimation(node, keepEntry);
    _UpdateAnimationIndices();
    return true;
}

