// 0x3f28ec LevelConfig::InitPost()
// The first call fills the empty camera file, camera name and the two light-set names with defaults, converts the
// ambient colour from 0..255 to 0..1, reads the isTracingLevel debug switch four times (the results are not used), and
// hands this config to the current level. Later calls do nothing. The empty test on each string is the original's
// comparison of the string's finish and data words (+0x10 and +0x14 of the string), which is std::string::empty().
// The base slot is void, so the original's return value (the result of Level::SetLevelConfig on the first call, or the
// object itself on later calls) is dropped.
void LevelConfig::InitPost() {
    if (!unk_29c) {                                              // +0x29c guard, set on the first call
        unk_29c = true;
        if (m_cameraFile.empty()) {                              // +0x24c
            m_cameraFile = "data/3D/camera/CameraTests.bdae";
        }
        if (m_cameraName.empty()) {                              // +0x27c
            m_cameraName = "PlayerCamera_Default";
        }
        if (m_lightSet.empty()) {                                // +0x2b8
            m_lightSet = "data/3D/Light/default.lightset_xml";
        }
        if (m_fixedLightSet.empty()) {                           // +0x2d0
            m_fixedLightSet = "data/3D/Light/default.lightset_xml";
        }
        Color255To01(m_ambientColor);                            // +0x1cc, divides the three components by 255

        // The original repeats this block four times with the same switch name. The values are discarded, and the
        // loads are repeated as the original does them.
        DebugSwitches::s_inst.load();
        DebugSwitches::s_inst.GetSwitch("isTracingLevel");
        DebugSwitches::s_inst.load();
        DebugSwitches::s_inst.GetSwitch("isTracingLevel");
        DebugSwitches::s_inst.load();
        DebugSwitches::s_inst.GetSwitch("isTracingLevel");
        DebugSwitches::s_inst.load();
        DebugSwitches::s_inst.GetSwitch("isTracingLevel");

        // Level::SetLevelConfig on the current level, which stores this config at Level +0x38. As in the original,
        // there is no null test on the level.
        ApplicationGetInstance().GetCurrentLevel()->SetLevelConfig(this);
    }
}

// 0x3f4910 LevelConfig::LevelConfig(ObjectBase::GO_IDS) (C2, complete object constructor)
// 0x3f51a8 LevelConfig::LevelConfig(ObjectBase::GO_IDS) (C1, base object constructor; the same body)
// ObjectBase is built first, and the compiler sets the vptrs of LevelConfig. The original then builds the strings in
// place (they start empty), writes zero to the Point3D members listed below and to the dfog vector, and clears the
// InitPost guard. The scalar properties in DeclareProperties (+0x1c8 onwards) are not written by the original
// constructor; their values come from the property defaults that LoadDefaultProperties sets.
LevelConfig::LevelConfig(ObjectBase::GO_IDS id) : ObjectBase(id) {
    m_ambientColor = Point3D<float>{};        // +0x1cc
    m_fogColor = Point3D<float>{};            // +0x1e0
    m_clearColor = Point3D<float>{};          // +0x1ec
    m_fogDirectionMask = Point3D<float>{};    // +0x1f8
    m_sunPosition = Point3D<float>{};         // +0x218
    m_shadowColor = Point3D<float>{};         // +0x224
    unk_29c = false;                          // +0x29c InitPost guard
}

// The constructor of SimpleTypeProperty<std::vector<Point3D<float>>> (object, name, field, default). The other slots of this
// instantiation are defined in game-items-save (cdc6b3-2); the constructor is not, so it is defined here. Property(name, begin,
// end) keeps the offset end - begin, so the object is the PropertyMap base and the field is the vector.
template <>
SimpleTypeProperty<std::vector<Point3D<float>>>::SimpleTypeProperty(void* object, const char* name,
                                                                    std::vector<Point3D<float>>* field,
                                                                    std::vector<Point3D<float>> defaultValue)
    : Property(name, object, field), m_defaultValue(std::move(defaultValue)) {}

// 0x3f4b9c LevelConfig::DeclareProperties()
// Registers the properties in the original order, each with its member and default: camera, music, fog and colour, sun,
// shadow, the names and light sets, the dfog distances, and the vertex and index buffer sizes. The "gametype" and
// "name" entries replace the ObjectBase entries of the same name. The default values are the bit patterns the pseudocode
// stores: 1132396544 is 255.0f, 1065353216 is 1.0f, -915135488 is -1000000.0f, 1128792064 is 200.0f and 1120403456 is
// 100.0f.
//
// "dfog_colors" (std::vector<Point3D<float>>, +0x204, offset 512 from the PropertyMap base) is registered after rim_light_file.
// The original builds a SimpleTypeProperty<std::vector<Point3D<float>>> with operator new(44), sets its name and offset,
// copies an empty vector as the default, and passes it to PropertyMap::AddProperty(name, Property*). dh2/SimpleTypeProperty.hpp
// declares the (object, name, field, default) constructor for that type, but no definition exists in src. The only
// definition is in game-items-save/tests/g1-game-items-save-SimpleTypeProperty-cdc6b3-2_test.cpp. Waits on that
// constructor. The registration is missing from the property table until then.
void LevelConfig::DeclareProperties() {
    AddProperty<std::string>("scriptFile", m_scriptFile);
    AddProperty<std::string>("camera_file", m_cameraFile);
    AddProperty<std::string>("camera_animset", m_cameraAnimset, std::string("Default"));
    AddProperty<std::string>("camera_name", m_cameraName);
    AddProperty<int>("camera_znear", m_cameraZnear, 600);
    AddProperty<int>("camera_zfar", m_cameraZfar, 10000);
    AddProperty<std::string>("skybox", m_skybox);
    AddProperty<std::string>("music", m_music);
    AddProperty<std::string>("combat_music", m_combatMusic);
    AddProperty<std::string>("ambiant_music", m_ambiantMusic);
    AddProperty<std::string>("safezone_music", m_safezoneMusic);
    AddProperty<bool>("combat_music_enabled", m_combatMusicEnabled, true);
    AddProperty<Point3D<float>>("ambientColor", m_ambientColor, Point3D<float>{255.0f, 255.0f, 255.0f});
    AddProperty<int>("fog_start", m_fogStart, 1);
    AddProperty<int>("fog_end", m_fogEnd, 0);
    AddProperty<Point3D<float>>("fog_color", m_fogColor, Point3D<float>{255.0f, 255.0f, 255.0f});
    AddProperty<Point3D<float>>("fog_direction_mask", m_fogDirectionMask, Point3D<float>{0.0f, 0.0f, 1.0f});
    AddProperty<Point3D<float>>("clear_color", m_clearColor, Point3D<float>{});
    AddProperty<Point3D<float>>("sun_position", m_sunPosition,
                                Point3D<float>{-1000000.0f, -1000000.0f, -1000000.0f});
    AddProperty<Point3D<float>>("shadow_color", m_shadowColor, Point3D<float>{});
    AddProperty<float>("shadow_opacity", m_shadowOpacity, 0.0f);
    AddProperty<std::string>("gametype", m_configGameType, std::string("LevelConfig"));
    AddProperty<std::string>("name", m_configName, std::string("level_config"));
    AddProperty<std::string>("light_set", m_lightSet, std::string());
    AddProperty<std::string>("fixed_light_set", m_fixedLightSet, std::string());
    AddProperty<std::string>("mp_script", m_mpScript, std::string());
    AddProperty<std::string>("rim_light_file", m_rimLightFile, std::string("char_rim_light.tga"));
    {
        // dfog_colors (+0x204): operator new(44), the name, the offset from the PropertyMap base (+0x200), the empty default.
        auto* dfog = new SimpleTypeProperty<std::vector<Point3D<float>>>(static_cast<PropertyMap*>(this), "dfog_colors",
                                                                         &m_dfogColors, std::vector<Point3D<float>>());
        Property* property = dfog;
        AddProperty("dfog_colors", property);
    }
    AddProperty<float>("dfog_change_min_dist", m_dfogChangeMinDist, 200.0f);
    AddProperty<float>("dfog_blend_dist", m_dfogBlendDist, 100.0f);
    AddProperty<int>("prog_vertex_buffer_size", m_progVertexBufferSize, 5242880);
    AddProperty<int>("prog_index_buffer_size", m_progIndexBufferSize, 655360);
    AddProperty<bool>("prog_quantize", m_progQuantize, false);
    AddProperty<int>("fix_vertex_buffer_size", m_fixVertexBufferSize, 5242880);
    AddProperty<int>("fix_index_buffer_size", m_fixIndexBufferSize, 655360);
    AddProperty<bool>("fix_quantize", m_fixQuantize, false);
}
